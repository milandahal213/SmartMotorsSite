"""Build docs/update/V3.py (the code the update portal uploads) from SmartMotors V3/.

The portal can't fetch from GitHub at runtime (rate limits in classrooms), so
this bundles every file listed in V3/toupload.py into one Python module that
the page imports. Run by .github/workflows/sync-motor-code.yml every hour.

    python scripts/build_motor_bundle.py --src path/to/SmartMotors/V3
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULTS = ROOT / "scripts" / "motor-defaults"

# Per-motor training data: always ship the starter files kept in this repo,
# never whatever test data happens to be in SmartMotors V3/.
USE_DEFAULTS = {"data.py", "trainData.txt"}

# Uploaded last, so the version stamp only lands once every other file did.
VERSION_FILE = "swv.py"

HEADER = '''\
# GENERATED by scripts/build_motor_bundle.py from tuftsceeo/SmartMotors V3/.
# Do not edit by hand: change V3/ in the SmartMotors repo instead.
# data.py and trainData.txt come from scripts/motor-defaults/ in this repo.
'''


def build(src: Path) -> str:
    manifest = json.loads((src / "toupload.py").read_text())["toupload"]
    if VERSION_FILE not in manifest:
        sys.exit(f"{VERSION_FILE} missing from toupload.py")
    order = [name for name in manifest if name != VERSION_FILE] + [VERSION_FILE]

    files = {}
    for name in order:
        path = (DEFAULTS if name in USE_DEFAULTS else src) / name
        if not path.is_file():
            sys.exit(f"Listed in toupload.py but not found: {path}")
        text = path.read_text()
        if name.endswith(".py") and name != VERSION_FILE:  # swv.py is a bare "3.1.1"
            compile(text, name, "exec")  # refuse to publish code that won't parse
        files[name] = text

    swv = files[VERSION_FILE].strip()
    lines = [HEADER, f"swv = {swv!r}", "", "code_list = {"]
    lines += [f"    {name!r}: {text!r}," for name, text in files.items()]
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--src", type=Path, required=True, help="SmartMotors V3/ folder")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "update" / "V3.py")
    args = parser.parse_args()

    args.out.write_text(build(args.src))
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
